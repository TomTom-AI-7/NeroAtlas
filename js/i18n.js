let lang = 'ja';
export function setLang(l) { lang = l === 'en' ? 'en' : 'ja'; document.documentElement.lang = lang; }
export function getLang() { return lang; }

/** Translate a UI key, or pick from a {ja,en} object / plain string. */
export function t(keyOrObj, vars) {
  let s;
  if (keyOrObj == null) return '';
  if (typeof keyOrObj === 'string') s = UI[keyOrObj] ? UI[keyOrObj][lang] : keyOrObj;
  else if (Array.isArray(keyOrObj)) return keyOrObj;
  else s = keyOrObj[lang] ?? keyOrObj.ja ?? keyOrObj.en ?? '';
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
